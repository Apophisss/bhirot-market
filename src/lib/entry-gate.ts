/**
 * שער הכניסה: מי שנכנס לאתר מקבל קודם כול את ההצעה לשחק.
 *
 * האתר יודע לומר "מצב זריז" בהרבה מקומות — בהירו, בסוף הרשימה, בפוטר, בדף השאלה —
 * אבל כולם דורשים שמישהו יגלול אליהם וילחץ. מי שנחת בדף הבית וגלל שלוש שניות עזב
 * בלי שאי פעם נאמר לו מה עושים כאן. השער אומר את זה מיד, לכל אחד — רשום ולא רשום —
 * ברגע הכניסה: שאלה אחרי שאלה, כן או לא, מתחילים.
 *
 * מודול עלים בלי תלויות, כמו `rapid-guest.ts`: הרכיב (`src/components/RapidEntryGate.tsx`)
 * והבדיקה (`scripts/test-entry-gate.ts`) משתמשים בו בלי לגרור שום דבר נוסף.
 */

/**
 * הזיכרון של השער חי ב-`sessionStorage` ולא ב-`localStorage` בכוונה: "כניסה לאתר"
 * היא ביקור, לא לחיצה. בתוך אותו ביקור ההצעה מוצגת פעם אחת (רענון של עמוד או מעבר
 * בין עמודים לא מקפיצים אותה שוב), ובכניסה הבאה — טאב חדש, חזרה מחר — היא חוזרת.
 */
const KEY = "bm_rapid_gate";

/**
 * הכתובות שלא מציגות את השער, וכל אחת מסיבה משלה:
 *
 * - `/rapid` — כבר משחקים שם. הצעה להיכנס למצב זריז מעל החפיסה היא בדיחה.
 * - `/login`, `/onboarding` — באמצע ההרשמה. חלון שמושך למקום אחר שם פשוט מפיל טופס.
 * - `/welcome` — דף הנחיתה של הפרסום, שכל כפתור בו ממילא מוביל ל-`/rapid`.
 * - `/i`, `/l` — הזמנה של חבר ושל ליגה: ההצעה שעל המסך היא ההזמנה עצמה, ואסור לה
 *   להיקבר מתחת לחלון.
 * - `/admin`, `/api` — לא עמודי שחקנים.
 */
export const GATE_SKIP_PATHS = ["/rapid", "/login", "/onboarding", "/welcome", "/i", "/l", "/admin", "/api"] as const;

/**
 * האם בכתובת הזאת מציגים את השער.
 *
 * ההשוואה היא לפי מקטעי הנתיב ולא לפי תחילית טקסטואלית: `/l` הוא דף ליגה, אבל
 * `/leaderboard` מתחיל באותן שתי אותיות ומקבל שער ככל עמוד אחר.
 */
export function pathWantsGate(path: string): boolean {
  if (!path || !path.startsWith("/")) return false;
  const clean = path.split(/[?#]/)[0].replace(/\/+$/, "") || "/";
  return !GATE_SKIP_PATHS.some((skip) => clean === skip || clean.startsWith(`${skip}/`));
}

/** האם ההצעה כבר הוצגה בביקור הזה. */
export function gateOffered(): boolean {
  try {
    return window.sessionStorage.getItem(KEY) === "1";
  } catch {
    // גלישה פרטית או אחסון חסום: אין זיכרון, ולכן ההצעה תוצג שוב בטעינה הבאה — זה
    // הכיוון הנכון לטעות בו, כי לחיצה אחת סוגרת אותה ואילו שער שלא הוצג הוא שער שאין
    return false;
  }
}

/** מסמן שההצעה הוצגה, כדי שלא תחזור בעמוד הבא באותו ביקור. */
export function markGateOffered(): void {
  try {
    window.sessionStorage.setItem(KEY, "1");
  } catch {
    /* אין אחסון — ראו `gateOffered` */
  }
}

/** שוכח את הביקור. קיים בשביל הבדיקות, ובשביל מי שרוצה לראות את השער שוב בדפדפן. */
export function resetGateOffered(): void {
  try {
    window.sessionStorage.removeItem(KEY);
  } catch {
    /* אין מה לשכוח */
  }
}
